import sys
from PySide6.QtWidgets import QApplication
from PySide6.QtGui import QGuiApplication

from app.theme import DARK_QSS
from app.consent_dialog import ConsentDialog
from app.main_window import MainWindow


def main():
    """Arranque de la app.

    1. Muestra el diálogo de consentimiento + contraseña.
    2. Si se acepta, abre la ventana principal con esa contraseña, que se usa
       para cifrar/descifrar el dataset durante toda la sesión.
    """
    app = QApplication(sys.argv)
    app.setStyleSheet(DARK_QSS)

    dialog = ConsentDialog()
    if dialog.exec() != ConsentDialog.Accepted:
        sys.exit(0)

    # La contraseña solo vive en memoria; nunca se escribe en disco
    password = dialog.password()

    w = MainWindow(password=password)
    geo = QGuiApplication.primaryScreen().availableGeometry()
    w.setGeometry(geo)
    w.show()
    sys.exit(app.exec())


if __name__ == "__main__":
    main()
