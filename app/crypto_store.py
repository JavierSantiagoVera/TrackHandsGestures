"""Cifrado del dataset y verificación de la contraseña.

Formato de todos los archivos cifrados:  [sal: 16 bytes][token Fernet]

- La sal es aleatoria por archivo; junto con la contraseña se pasa por
  PBKDF2-HMAC-SHA256 para obtener la clave (así la misma contraseña genera
  claves distintas en cada archivo).
- Fernet (AES + HMAC) es autenticado: con una contraseña incorrecta lanza
  InvalidToken en vez de devolver basura.
"""
import io
import os
import base64

import numpy as np
from cryptography.fernet import Fernet, InvalidToken
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC

_SALT_SIZE = 16
_ITERATIONS = 390_000
_VERIFIER_PHRASE = b"cho kawaii gyaru"  # 💅 gyaru approved ✨


def _derive_key(password: str, salt: bytes) -> bytes:
    # Muchas iteraciones = probar contraseñas por fuerza bruta es lento
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(),
        length=32,
        salt=salt,
        iterations=_ITERATIONS,
    )
    return base64.urlsafe_b64encode(kdf.derive(password.encode("utf-8")))


def _write_atomic(path: str, data: bytes) -> None:
    # Escribe a un temporal y luego lo renombra: si la app se cierra a mitad,
    # el archivo original queda intacto
    tmp = path + ".tmp"
    with open(tmp, "wb") as fp:
        fp.write(data)
    os.replace(tmp, path)


def create_verifier(path: str, password: str) -> None:
    """Store the known phrase encrypted with the password."""
    salt = os.urandom(_SALT_SIZE)
    token = Fernet(_derive_key(password, salt)).encrypt(_VERIFIER_PHRASE)
    _write_atomic(path, salt + token)


def check_verifier(path: str, password: str) -> bool:
    """True if the password decrypts the verifier back to the known phrase."""
    with open(path, "rb") as fp:
        raw = fp.read()
    salt, token = raw[:_SALT_SIZE], raw[_SALT_SIZE:]
    try:
        return Fernet(_derive_key(password, salt)).decrypt(token) == _VERIFIER_PHRASE
    except InvalidToken:
        return False


def save_encrypted(path: str, X: np.ndarray, y: np.ndarray, password: str) -> None:
    """Compress numpy arrays and write AES-encrypted to path."""
    salt = os.urandom(_SALT_SIZE)
    key = _derive_key(password, salt)
    f = Fernet(key)

    # Se serializa en memoria (nunca se escribe el .npz sin cifrar a disco)
    buf = io.BytesIO()
    np.savez_compressed(buf, X=X, y=y)
    encrypted = f.encrypt(buf.getvalue())

    _write_atomic(path, salt + encrypted)


def load_encrypted(path: str, password: str):
    """Return (X, y) from an encrypted file. Raises InvalidToken on wrong password."""
    with open(path, "rb") as fp:
        raw = fp.read()

    salt, encrypted = raw[:_SALT_SIZE], raw[_SALT_SIZE:]
    key = _derive_key(password, salt)
    data = Fernet(key).decrypt(encrypted)  # raises InvalidToken if wrong password

    buf = io.BytesIO(data)
    d = np.load(buf, allow_pickle=False)
    return d["X"].astype(np.float32), d["y"].astype(np.int64)
